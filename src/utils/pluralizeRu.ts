/**
 * Утилита склонения русских существительных и словосочетаний по целому числу.
 * Переиспользуется в модулях обратного отсчёта дат и общей сводки готовности блога.
 */

/**
 * Возвращает корректную русскую словоформу для переданного целого числа.
 * @param count Целое число (знак игнорируется через Math.abs).
 * @param one Форма для чисел, оканчивающихся на 1, кроме 11 (например, «день», «арт»).
 * @param few Форма для 2–4, кроме 12–14 (например, «дня», «арта»).
 * @param many Форма для 0, 5–20 и остальных случаев (например, «дней», «артов»).
 * @returns Подходящая словоформа.
 */
export function pluralizeRu(count: number, one: string, few: string, many: string): string {
  const mod100 = Math.abs(count) % 100;
  const mod10 = mod100 % 10;

  if (mod100 >= 11 && mod100 <= 19) {
    return many;
  }
  if (mod10 === 1) {
    return one;
  }
  if (mod10 >= 2 && mod10 <= 4) {
    return few;
  }
  return many;
}
